"""Reference-matching experiment computed from complete annotations.

This module consumes the benchmark annotation JSONL itself.  It does not read
or replay precomputed counts, so it can score either the authoritative Data
artifact or annotations freshly regenerated by the public system runners.
"""

from __future__ import annotations

import random
from collections.abc import Callable, Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from .schema import DatasetSpec


@dataclass(frozen=True)
class MatchEdit:
    start: int
    end: int
    label: str

    @property
    def span(self) -> tuple[int, int]:
        return self.start, self.end


@dataclass(frozen=True)
class Counts:
    tp: int
    fp: int
    fn: int


def spans_overlap(left: tuple[int, int], right: tuple[int, int]) -> bool:
    if left[0] == left[1] and right[0] == right[1]:
        return left[0] == right[0]
    if left[0] == left[1]:
        return right[0] < left[0] < right[1]
    if right[0] == right[1]:
        return left[0] < right[0] < left[1]
    return max(0, min(left[1], right[1]) - max(left[0], right[0])) > 0


def exact_span(left: tuple[int, int], right: tuple[int, int]) -> bool:
    return left == right


def _overlap_size(left: tuple[int, int], right: tuple[int, int]) -> int:
    if left[0] == left[1] or right[0] == right[1]:
        return 1 if spans_overlap(left, right) else 0
    return max(0, min(left[1], right[1]) - max(left[0], right[0]))


def _is_artifact_char(source: str, start: int, end: int, replacement: Any) -> bool:
    span = source[start:end]
    replacement_text = str(replacement or "")
    return (
        span.strip() == "" and replacement_text.strip() == ""
    ) or span == replacement_text


def _is_artifact_token(raw_edit: Mapping[str, Any]) -> bool:
    char_source = raw_edit.get("char_src")
    if char_source is None:
        return False
    char_source = str(char_source)
    char_replacement = str(raw_edit.get("char_repl") or "")
    return (
        char_source.strip() == "" and char_replacement.strip() == ""
    ) or char_source == char_replacement


def edits_from_row(
    row: Mapping[str, Any], system: str, spec: DatasetSpec
) -> list[MatchEdit]:
    raw_edits = row.get(system)
    if not isinstance(raw_edits, list):
        raise ValueError(f"{spec.dataset_id}: {system} annotations must be a list")
    is_reference = system == "gold"
    output: list[MatchEdit] = []
    if spec.edit_format == "char_tuple":
        source = str(row.get("src", ""))
        for raw_edit in raw_edits:
            start, end, mapped_label, _raw_label, replacement = raw_edit
            start = int(start)
            end = int(end)
            if not is_reference and _is_artifact_char(
                source, start, end, replacement
            ):
                continue
            output.append(MatchEdit(start, end, str(mapped_label)))
        return output

    for raw_edit in raw_edits:
        if not isinstance(raw_edit, Mapping):
            raise ValueError(f"{spec.dataset_id}: malformed token edit")
        if not is_reference and _is_artifact_token(raw_edit):
            continue
        label = raw_edit.get("target", raw_edit.get("raw_label", ""))
        output.append(
            MatchEdit(
                int(raw_edit["orig_start"]),
                int(raw_edit["orig_end"]),
                str(label),
            )
        )
    return output


def match_indices(
    system: Sequence[MatchEdit],
    reference: Sequence[MatchEdit],
    *,
    span_predicate: Callable[[tuple[int, int], tuple[int, int]], bool],
    require_label: bool,
) -> list[tuple[int, int]]:
    if require_label and any(not edit.label for edit in (*system, *reference)):
        raise ValueError("typed reference matching requires non-empty mapped labels")
    edges_by_reference: list[list[tuple[int, int]]] = [
        [] for _ in reference
    ]
    for reference_index, gold_edit in enumerate(reference):
        for system_index, system_edit in enumerate(system):
            if not span_predicate(system_edit.span, gold_edit.span):
                continue
            if require_label and system_edit.label != gold_edit.label:
                continue
            edges_by_reference[reference_index].append(
                (_overlap_size(system_edit.span, gold_edit.span), system_index)
            )
    for edges in edges_by_reference:
        edges.sort(key=lambda value: (-value[0], value[1]))

    matched_system: dict[int, int] = {}

    def augment(reference_index: int, seen_system: set[int]) -> bool:
        for _score, system_index in edges_by_reference[reference_index]:
            if system_index in seen_system:
                continue
            seen_system.add(system_index)
            previous_reference = matched_system.get(system_index)
            if previous_reference is None or augment(previous_reference, seen_system):
                matched_system[system_index] = reference_index
                return True
        return False

    reference_order = sorted(
        range(len(reference)),
        key=lambda index: (
            len(edges_by_reference[index]),
            -max((score for score, _ in edges_by_reference[index]), default=0),
            index,
        ),
    )
    for reference_index in reference_order:
        if edges_by_reference[reference_index]:
            augment(reference_index, set())
    return sorted(matched_system.items())


def match_counts(
    system: Sequence[MatchEdit],
    reference: Sequence[MatchEdit],
    *,
    span_predicate: Callable[[tuple[int, int], tuple[int, int]], bool],
    require_label: bool,
) -> Counts:
    true_positives = len(
        match_indices(
            system,
            reference,
            span_predicate=span_predicate,
            require_label=require_label,
        )
    )
    return Counts(
        true_positives,
        len(system) - true_positives,
        len(reference) - true_positives,
    )


def _sum_counts(values: Iterable[Counts]) -> Counts:
    tp = fp = fn = 0
    for value in values:
        tp += value.tp
        fp += value.fp
        fn += value.fn
    return Counts(tp, fp, fn)


def fbeta(counts: Counts, beta: float = 0.5) -> dict[str, float | int]:
    precision = counts.tp / (counts.tp + counts.fp) if counts.tp + counts.fp else 0.0
    recall = counts.tp / (counts.tp + counts.fn) if counts.tp + counts.fn else 0.0
    beta_squared = beta * beta
    score = (
        (1 + beta_squared)
        * precision
        * recall
        / (beta_squared * precision + recall)
        if precision or recall
        else 0.0
    )
    return {
        "tp": counts.tp,
        "fp": counts.fp,
        "fn": counts.fn,
        "precision": precision,
        "recall": recall,
        "f0.5": score,
    }


def _bootstrap_f05(
    per_item: Sequence[Counts], *, samples: int, seed: int
) -> tuple[float, float]:
    if not per_item:
        raise ValueError("reference bootstrap requires benchmark items")
    if samples <= 0:
        raise ValueError("reference bootstrap samples must be positive")
    rng = random.Random(seed)
    count = len(per_item)
    distribution: list[float] = []
    for _ in range(samples):
        aggregate = _sum_counts(
            per_item[rng.randrange(count)] for _ in range(count)
        )
        distribution.append(float(fbeta(aggregate)["f0.5"]))
    distribution.sort()
    return (
        distribution[int(0.025 * samples)],
        distribution[min(samples - 1, int(0.975 * samples))],
    )


def score_reference_matching(
    rows: Sequence[Mapping[str, Any]],
    spec: DatasetSpec,
    *,
    annotation_source: str,
    span_match: str = "overlap",
    samples: int = 1000,
    seed: int = 42,
) -> list[dict[str, Any]]:
    """Recompute one complete paper reference-matching table from annotations."""

    if annotation_source not in {"authoritative_frozen", "fresh_rerun"}:
        raise ValueError(
            "annotation_source must be 'authoritative_frozen' or 'fresh_rerun'"
        )
    try:
        span_predicate = {"overlap": spans_overlap, "exact": exact_span}[span_match]
    except KeyError as error:
        raise ValueError(f"unknown span matching policy: {span_match!r}") from error
    systems = tuple(system for system in spec.systems if system != "gold")
    references = [edits_from_row(row, "gold", spec) for row in rows]
    output: list[dict[str, Any]] = []
    for system in systems:
        system_edits = [edits_from_row(row, system, spec) for row in rows]
        detection = [
            match_counts(
                predicted,
                gold,
                span_predicate=span_predicate,
                require_label=False,
            )
            for predicted, gold in zip(system_edits, references, strict=True)
        ]
        classification = [
            match_counts(
                predicted,
                gold,
                span_predicate=span_predicate,
                require_label=True,
            )
            for predicted, gold in zip(system_edits, references, strict=True)
        ]
        detection_metrics = fbeta(_sum_counts(detection))
        classification_metrics = fbeta(_sum_counts(classification))
        detection_interval = _bootstrap_f05(detection, samples=samples, seed=seed)
        classification_interval = _bootstrap_f05(
            classification, samples=samples, seed=seed
        )
        output.append(
            {
                "annotation_source": annotation_source,
                "span_match": span_match,
                "system": system,
                "h1_span_f05": detection_metrics["f0.5"],
                "h1_span_ci_low": detection_interval[0],
                "h1_span_ci_high": detection_interval[1],
                "h1_span_precision": detection_metrics["precision"],
                "h1_span_recall": detection_metrics["recall"],
                "h1_span_tp": detection_metrics["tp"],
                "h1_span_fp": detection_metrics["fp"],
                "h1_span_fn": detection_metrics["fn"],
                "h2_typed_f05": classification_metrics["f0.5"],
                "h2_typed_ci_low": classification_interval[0],
                "h2_typed_ci_high": classification_interval[1],
                "h2_typed_precision": classification_metrics["precision"],
                "h2_typed_recall": classification_metrics["recall"],
                "h2_typed_tp": classification_metrics["tp"],
                "h2_typed_fp": classification_metrics["fp"],
                "h2_typed_fn": classification_metrics["fn"],
                "n_sentences": len(rows),
            }
        )
    return output
